// App (menu) language for contractors. English text is the key; Spanish
// translations live in ES below. Customer-facing invoice wording is in i18n.ts.
export type UiLang = "en" | "es";
export const UI_COOKIE = "vb_lang";

export function uiLang(value: unknown): UiLang {
  return value === "es" ? "es" : "en";
}

/**
 * Translates an English UI string. Use {name} placeholders for values:
 * tr("es", "{n} of {limit} free notes left", { n: 3, limit: 5 }).
 * Missing Spanish entries fall back to English (a test checks there are none).
 */
export function tr(lang: UiLang, en: string, vars?: Record<string, string | number>): string {
  let s = lang === "es" ? (ES[en] ?? en) : en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** A translator bound to one language. */
export function translator(lang: UiLang) {
  return (en: string, vars?: Record<string, string | number>) => tr(lang, en, vars);
}

